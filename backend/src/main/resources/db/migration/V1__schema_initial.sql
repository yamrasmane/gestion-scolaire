-- =====================================================================
-- Système de gestion scolaire — schéma initial (22 tables métiers)
-- Toutes les tables portent le socle d'audit : created_at, created_by,
-- updated_at, updated_by, version (SF-19).
-- =====================================================================

-- ---------- Volet académique ----------

CREATE TABLE annee_scolaire (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle                   VARCHAR(20)  NOT NULL UNIQUE,
    date_debut                DATE         NOT NULL,
    date_fin                  DATE         NOT NULL,
    avec_composition_defaut   BOOLEAN      NOT NULL DEFAULT TRUE,
    poids_composition_defaut  NUMERIC(4,2) NOT NULL DEFAULT 2,
    bloquer_bulletin_impaye   BOOLEAN      NOT NULL DEFAULT FALSE,
    actif                     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_annee_dates CHECK (date_fin > date_debut),
    CONSTRAINT ck_annee_poids CHECK (poids_composition_defaut > 0)
);
-- Une seule année scolaire active à la fois (SF-01)
CREATE UNIQUE INDEX ux_annee_scolaire_active ON annee_scolaire (actif) WHERE actif;

CREATE TABLE trimestre (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee_scolaire_id  BIGINT  NOT NULL REFERENCES annee_scolaire (id),
    numero             INTEGER NOT NULL,
    date_debut         DATE    NOT NULL,
    date_fin           DATE    NOT NULL,
    avec_composition   BOOLEAN,
    poids_composition  NUMERIC(4,2),
    cloture            BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_trimestre UNIQUE (annee_scolaire_id, numero),
    CONSTRAINT ck_trimestre_numero CHECK (numero IN (1, 2, 3)),
    CONSTRAINT ck_trimestre_dates CHECK (date_fin > date_debut),
    CONSTRAINT ck_trimestre_poids CHECK (poids_composition IS NULL OR poids_composition > 0)
);

CREATE TABLE config_composition_cycle (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trimestre_id       BIGINT       NOT NULL REFERENCES trimestre (id),
    cycle              VARCHAR(10)  NOT NULL,
    avec_composition   BOOLEAN      NOT NULL,
    poids_composition  NUMERIC(4,2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_config_composition_cycle UNIQUE (trimestre_id, cycle),
    CONSTRAINT ck_config_cycle CHECK (cycle IN ('PREMIER', 'SECOND')),
    CONSTRAINT ck_config_poids CHECK (poids_composition > 0)
);

CREATE TABLE niveau (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(20)  NOT NULL UNIQUE,
    libelle  VARCHAR(100) NOT NULL,
    cycle    VARCHAR(10)  NOT NULL,
    ordre    INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_niveau_cycle CHECK (cycle IN ('PREMIER', 'SECOND'))
);

CREATE TABLE classe (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    niveau_id          BIGINT      NOT NULL REFERENCES niveau (id),
    annee_scolaire_id  BIGINT      NOT NULL REFERENCES annee_scolaire (id),
    nom                VARCHAR(50) NOT NULL,
    effectif_max       INTEGER     NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_classe UNIQUE (annee_scolaire_id, nom),
    CONSTRAINT ck_classe_effectif CHECK (effectif_max > 0)
);

CREATE TABLE personnel (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id  UUID UNIQUE,
    matricule    VARCHAR(30)  NOT NULL UNIQUE,
    nom          VARCHAR(100) NOT NULL,
    prenom       VARCHAR(100) NOT NULL,
    email        VARCHAR(150) NOT NULL UNIQUE,
    telephone    VARCHAR(30),
    role         VARCHAR(20)  NOT NULL,
    actif        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_personnel_role CHECK (role IN
        ('DIRECTEUR', 'CENSEUR', 'ENSEIGNANT', 'INTENDANT', 'ECONOME', 'SURVEILLANT'))
);

CREATE TABLE eleve (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule       VARCHAR(30)  NOT NULL UNIQUE,
    nom             VARCHAR(100) NOT NULL,
    prenom          VARCHAR(100) NOT NULL,
    date_naissance  DATE         NOT NULL,
    sexe            VARCHAR(1)   NOT NULL,
    nom_parent      VARCHAR(150),
    contact_parent  VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_eleve_sexe CHECK (sexe IN ('M', 'F'))
);

-- ---------- Volet financier : paramétrage ----------

CREATE TABLE type_frais (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(30)  NOT NULL UNIQUE,
    libelle              VARCHAR(100) NOT NULL,
    obligatoire          BOOLEAN      NOT NULL DEFAULT TRUE,
    fractionnable        BOOLEAN      NOT NULL DEFAULT FALSE,
    priorite_imputation  INTEGER      NOT NULL DEFAULT 100,
    actif                BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE grille_tarifaire (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee_scolaire_id  BIGINT        NOT NULL REFERENCES annee_scolaire (id),
    type_frais_id      BIGINT        NOT NULL REFERENCES type_frais (id),
    niveau_id          BIGINT        REFERENCES niveau (id),
    classe_id          BIGINT        REFERENCES classe (id),
    categorie          VARCHAR(10)   NOT NULL DEFAULT 'TOUS',
    montant            NUMERIC(12,0) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_grille_categorie CHECK (categorie IN ('NOUVEAU', 'ANCIEN', 'TOUS')),
    CONSTRAINT ck_grille_montant CHECK (montant >= 0),
    -- Un tarif vise soit un niveau, soit une classe précise (SF-22)
    CONSTRAINT ck_grille_cible CHECK ((niveau_id IS NULL) <> (classe_id IS NULL))
);
CREATE UNIQUE INDEX ux_grille_tarifaire ON grille_tarifaire
    (annee_scolaire_id, type_frais_id, COALESCE(niveau_id, 0), COALESCE(classe_id, 0), categorie);

CREATE TABLE plan_paiement (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee_scolaire_id        BIGINT       NOT NULL REFERENCES annee_scolaire (id),
    libelle                  VARCHAR(100) NOT NULL,
    niveau_id                BIGINT       REFERENCES niveau (id),
    classe_id                BIGINT       REFERENCES classe (id),
    categorie                VARCHAR(10),
    mode_repartition         VARCHAR(15)  NOT NULL,
    par_defaut               BOOLEAN      NOT NULL DEFAULT FALSE,
    montant_min_inscription  NUMERIC(12,0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_plan_paiement UNIQUE (annee_scolaire_id, libelle),
    CONSTRAINT ck_plan_categorie CHECK (categorie IS NULL OR categorie IN ('NOUVEAU', 'ANCIEN')),
    CONSTRAINT ck_plan_mode CHECK (mode_repartition IN ('POURCENTAGE', 'MONTANT')),
    CONSTRAINT ck_plan_cible CHECK (niveau_id IS NULL OR classe_id IS NULL)
);
-- Un seul plan par défaut par année scolaire (SF-26)
CREATE UNIQUE INDEX ux_plan_paiement_defaut ON plan_paiement (annee_scolaire_id) WHERE par_defaut;

CREATE TABLE tranche_paiement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_paiement_id  BIGINT       NOT NULL REFERENCES plan_paiement (id),
    numero            INTEGER      NOT NULL,
    libelle           VARCHAR(100) NOT NULL,
    date_echeance     DATE         NOT NULL,
    pourcentage       NUMERIC(5,2),
    montant           NUMERIC(12,0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_tranche_paiement UNIQUE (plan_paiement_id, numero),
    CONSTRAINT ck_tranche_numero CHECK (numero >= 1),
    -- La part d'une tranche est exprimée en pourcentage OU en montant fixe
    CONSTRAINT ck_tranche_part CHECK ((pourcentage IS NULL) <> (montant IS NULL)),
    CONSTRAINT ck_tranche_pourcentage CHECK (pourcentage IS NULL OR (pourcentage > 0 AND pourcentage <= 100)),
    CONSTRAINT ck_tranche_montant CHECK (montant IS NULL OR montant >= 0)
);

-- ---------- Inscriptions et scolarité ----------

CREATE TABLE inscription (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eleve_id           BIGINT      NOT NULL REFERENCES eleve (id),
    classe_id          BIGINT      NOT NULL REFERENCES classe (id),
    annee_scolaire_id  BIGINT      NOT NULL REFERENCES annee_scolaire (id),
    categorie          VARCHAR(10) NOT NULL,
    categorie_forcee   BOOLEAN     NOT NULL DEFAULT FALSE,
    motif_categorie    VARCHAR(255),
    redoublant         BOOLEAN     NOT NULL DEFAULT FALSE,
    plan_paiement_id   BIGINT      REFERENCES plan_paiement (id),
    date_inscription   DATE        NOT NULL,
    statut             VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_inscription UNIQUE (eleve_id, annee_scolaire_id),
    CONSTRAINT ck_inscription_categorie CHECK (categorie IN ('NOUVEAU', 'ANCIEN')),
    CONSTRAINT ck_inscription_statut CHECK (statut IN ('ACTIVE', 'ANNULEE')),
    CONSTRAINT ck_inscription_motif CHECK (NOT categorie_forcee OR motif_categorie IS NOT NULL)
);
CREATE INDEX ix_inscription_classe ON inscription (classe_id);

CREATE TABLE matiere (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(20)  NOT NULL UNIQUE,
    libelle  VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE enseignement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classe_id      BIGINT       NOT NULL REFERENCES classe (id),
    matiere_id     BIGINT       NOT NULL REFERENCES matiere (id),
    enseignant_id  BIGINT       REFERENCES personnel (id),
    coefficient    NUMERIC(4,1) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_enseignement UNIQUE (classe_id, matiere_id),
    CONSTRAINT ck_enseignement_coefficient CHECK (coefficient > 0)
);
CREATE INDEX ix_enseignement_enseignant ON enseignement (enseignant_id);

CREATE TABLE evaluation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enseignement_id  BIGINT       NOT NULL REFERENCES enseignement (id),
    trimestre_id     BIGINT       NOT NULL REFERENCES trimestre (id),
    categorie        VARCHAR(15)  NOT NULL,
    libelle          VARCHAR(50)  NOT NULL,
    date_eval        DATE,
    bareme           NUMERIC(4,1) NOT NULL DEFAULT 20,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_evaluation UNIQUE (enseignement_id, trimestre_id, libelle),
    CONSTRAINT ck_evaluation_categorie CHECK (categorie IN ('DEVOIR', 'COMPOSITION'))
);
-- Une seule composition par enseignement et par trimestre (SF-11)
CREATE UNIQUE INDEX ux_evaluation_composition ON evaluation (enseignement_id, trimestre_id)
    WHERE categorie = 'COMPOSITION';

CREATE TABLE note (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id   BIGINT  NOT NULL REFERENCES evaluation (id),
    inscription_id  BIGINT  NOT NULL REFERENCES inscription (id),
    valeur          NUMERIC(4,2),
    absent          BOOLEAN NOT NULL DEFAULT FALSE,
    appreciation    VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_note UNIQUE (evaluation_id, inscription_id),
    CONSTRAINT ck_note_valeur CHECK (valeur IS NULL OR (valeur >= 0 AND valeur <= 20))
);
CREATE INDEX ix_note_inscription ON note (inscription_id);

CREATE TABLE bulletin (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscription_id        BIGINT  NOT NULL REFERENCES inscription (id),
    trimestre_id          BIGINT  NOT NULL REFERENCES trimestre (id),
    total_coefficients    NUMERIC(6,1),
    total_points          NUMERIC(8,2),
    moyenne_generale      NUMERIC(4,2),
    rang                  INTEGER,
    ex_aequo              BOOLEAN NOT NULL DEFAULT FALSE,
    mention               VARCHAR(30),
    appreciation_conseil  VARCHAR(500),
    bloque_impaye         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_bulletin UNIQUE (inscription_id, trimestre_id)
);

CREATE TABLE lot_impression (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trimestre_id   BIGINT      NOT NULL REFERENCES trimestre (id),
    cible          VARCHAR(15) NOT NULL,
    cible_id       BIGINT,
    format_sortie  VARCHAR(15) NOT NULL,
    statut         VARCHAR(15) NOT NULL DEFAULT 'EN_ATTENTE',
    progression    INTEGER     NOT NULL DEFAULT 0,
    url_fichier    VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_lot_cible CHECK (cible IN ('CLASSE', 'NIVEAU', 'ETABLISSEMENT')),
    CONSTRAINT ck_lot_format CHECK (format_sortie IN ('PDF_FUSIONNE', 'ZIP')),
    CONSTRAINT ck_lot_statut CHECK (statut IN ('EN_ATTENTE', 'EN_COURS', 'TERMINE', 'ECHEC')),
    CONSTRAINT ck_lot_progression CHECK (progression BETWEEN 0 AND 100)
);

-- ---------- Volet financier : frais, échéances, paiements ----------

CREATE TABLE frais_eleve (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscription_id      BIGINT        NOT NULL REFERENCES inscription (id),
    type_frais_id       BIGINT        NOT NULL REFERENCES type_frais (id),
    montant_brut        NUMERIC(12,0) NOT NULL,
    remise_type         VARCHAR(15),
    remise_valeur       NUMERIC(12,2),
    montant_remise      NUMERIC(12,0) NOT NULL DEFAULT 0,
    montant_net         NUMERIC(12,0) NOT NULL,
    motif_remise        VARCHAR(255),
    remise_validee_par  VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_frais_eleve UNIQUE (inscription_id, type_frais_id),
    CONSTRAINT ck_frais_remise_type CHECK (remise_type IS NULL OR remise_type IN ('POURCENTAGE', 'MONTANT')),
    CONSTRAINT ck_frais_montants CHECK (montant_brut >= 0 AND montant_remise >= 0
        AND montant_net = montant_brut - montant_remise AND montant_net >= 0),
    CONSTRAINT ck_frais_motif_remise CHECK (montant_remise = 0 OR motif_remise IS NOT NULL)
);

CREATE TABLE echeance_eleve (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    frais_eleve_id       BIGINT        NOT NULL REFERENCES frais_eleve (id),
    tranche_paiement_id  BIGINT        REFERENCES tranche_paiement (id),
    date_echeance        DATE          NOT NULL,
    montant_du           NUMERIC(12,0) NOT NULL,
    montant_paye         NUMERIC(12,0) NOT NULL DEFAULT 0,
    statut               VARCHAR(15)   NOT NULL DEFAULT 'A_VENIR',
    derogatoire          BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_echeance_statut CHECK (statut IN ('A_VENIR', 'PARTIEL', 'PAYEE', 'EN_RETARD')),
    CONSTRAINT ck_echeance_montants CHECK (montant_du >= 0 AND montant_paye >= 0 AND montant_paye <= montant_du)
);
CREATE INDEX ix_echeance_frais ON echeance_eleve (frais_eleve_id);
CREATE INDEX ix_echeance_retard ON echeance_eleve (date_echeance) WHERE statut <> 'PAYEE';

CREATE TABLE paiement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_recu       VARCHAR(30)   NOT NULL UNIQUE,
    inscription_id    BIGINT        NOT NULL REFERENCES inscription (id),
    date_paiement     DATE          NOT NULL,
    montant           NUMERIC(12,0) NOT NULL,
    mode              VARCHAR(15)   NOT NULL,
    reference         VARCHAR(100),
    payeur            VARCHAR(150),
    caissier_id       BIGINT        REFERENCES personnel (id),
    statut            VARCHAR(10)   NOT NULL DEFAULT 'VALIDE',
    motif_annulation  VARCHAR(255),
    annule_par        VARCHAR(100),
    journee_caisse    DATE          NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_paiement_montant CHECK (montant > 0),
    CONSTRAINT ck_paiement_mode CHECK (mode IN ('ESPECES', 'MOBILE_MONEY', 'VIREMENT', 'CHEQUE')),
    CONSTRAINT ck_paiement_statut CHECK (statut IN ('VALIDE', 'ANNULE')),
    -- Une annulation exige un motif et son auteur (SF-30)
    CONSTRAINT ck_paiement_annulation CHECK (statut <> 'ANNULE'
        OR (motif_annulation IS NOT NULL AND annule_par IS NOT NULL))
);
CREATE INDEX ix_paiement_inscription ON paiement (inscription_id);
CREATE INDEX ix_paiement_journee ON paiement (journee_caisse);

CREATE TABLE imputation_paiement (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paiement_id        BIGINT        NOT NULL REFERENCES paiement (id),
    echeance_eleve_id  BIGINT        NOT NULL REFERENCES echeance_eleve (id),
    montant            NUMERIC(12,0) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE, updated_by VARCHAR(100), version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ux_imputation UNIQUE (paiement_id, echeance_eleve_id),
    CONSTRAINT ck_imputation_montant CHECK (montant > 0)
);
CREATE INDEX ix_imputation_echeance ON imputation_paiement (echeance_eleve_id);
